// Current language (default: FR)
let currentLang = 'fr';

/**
 * Get a translation by key
 */
function t(key) {
  const lang = translations[currentLang] || translations.fr;
  return lang[key] || translations.fr[key] || key;
}

/**
 * Set the active language and apply translations
 */
function setLanguage(lang) {
  if (!translations[lang]) lang = 'fr';
  currentLang = lang;
  localStorage.setItem('useflow_lang', lang);
  applyTranslations();

  // Re-render sections whose labels are generated dynamically.
  if (typeof loadSourceManager === 'function' && document.getElementById('section-sources')?.classList.contains('active')) {
    loadSourceManager();
  }
  if (typeof loadCatalogManager === 'function' && document.getElementById('section-catalogs')?.classList.contains('active')) {
    loadCatalogManager();
  }

  // Update select if it exists
  const select = document.getElementById('langSelect');
  if (select) select.value = lang;
}

/**
 * Apply translations to all elements with data-i18n attribute
 */
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = t(key);
    if (value) {
      // For elements that contain HTML (like descriptions), use innerHTML
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = value;
      } else if (el.tagName === 'INPUT' && el.type !== 'checkbox') {
        // For inputs, set placeholder
        if (el.hasAttribute('data-i18n-placeholder')) {
          el.placeholder = value;
        }
      } else {
        el.textContent = value;
      }
    }
  });
}

/**
 * Initialize i18n - call this on page load
 */
function initI18n() {
  const saved = localStorage.getItem('useflow_lang');
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    // Try to detect from browser
    const browserLang = navigator.language?.substring(0, 2);
    if (translations[browserLang]) {
      currentLang = browserLang;
    }
  }

  // Set select value
  const select = document.getElementById('langSelect');
  if (select) select.value = currentLang;

  applyTranslations();
}
